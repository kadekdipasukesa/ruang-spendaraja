/**
 * Bersihkan string untuk pencocokan toleran
 */
function cleanStr(str) {
  if (!str) return "";
  return str
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "")
    .trim();
}

/**
 * Verifikasi apakah siswa terdaftar sebagai anggota resmi Ekstra TIK
 */
export function cariAnggotaEkstra({ nama, kelas, noAbsen }) {
  if (!nama) return null;

  const targetNameClean = cleanStr(nama);
  const targetAbsen = noAbsen ? parseInt(noAbsen, 10) : null;

  // 1. Cek kecocokan nama persis / sangat mirip
  for (const a of ANGGOTA_EKSTRA_TIK) {
    const aNameClean = cleanStr(a.nama);
    if (targetNameClean === aNameClean) {
      return a;
    }
    // Jika nama mengandung substring panjang yang khas (min 8 karakter)
    if (
      targetNameClean.length >= 8 &&
      (targetNameClean.includes(aNameClean) || aNameClean.includes(targetNameClean))
    ) {
      return a;
    }
  }

  // 2. Cek kecocokan kombinasi Kelas + No Absen
  if (kelas && targetAbsen) {
    const titikKelas = KELAS_MAP_HURUF_KE_TITIK[kelas.toUpperCase()] || kelas;
    const match = ANGGOTA_EKSTRA_TIK.find(
      (a) =>
        (a.kelas === titikKelas || KELAS_MAP_TITIK_KE_HURUF[a.kelas] === kelas.toUpperCase()) &&
        parseInt(a.noAbsen, 10) === targetAbsen
    );
    if (match) return match;
  }

  return null;
}
