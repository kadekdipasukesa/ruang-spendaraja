/**
 * Mencari panduan materi/fitur yang relevan dari pesan siswa berdasarkan kata kunci
 * @param {string} userMessage - Pesan chat dari siswa
 * @returns {object|null} Objek panduan pengetahuan yang paling cocok atau null
 */
export function findRelevantKnowledge(userMessage = "") {
  if (!userMessage || typeof userMessage !== "string") return null;

  const normalized = userMessage.toLowerCase().trim();

  // 1. Prioritas pencocokan kata kunci tugas spesifik (tugas 4 tahap 2, dsb)
  for (const item of AI_KNOWLEDGE_BANK) {
    const hasMatch = item.keywords.some((kw) => {
      // Cocokkan frasa kata kunci
      return normalized.includes(kw);
    });

    if (hasMatch) {
      return item;
    }
  }

  return null;
}
